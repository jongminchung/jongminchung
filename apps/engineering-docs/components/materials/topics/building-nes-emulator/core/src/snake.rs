/// 스네이크 게임이 도는 가짜 콘솔의 버스.
/// 평평한 64KB 메모리에 특별한 주소 둘이 있다:
/// $FE를 읽으면 난수가 나오고, $FF에는 마지막 키 입력이 들어 있다.
pub struct SnakeBus {
    pub mem: Box<[u8; 0x10000]>,
    rng: u64,
}

impl SnakeBus {
    pub fn new(seed: u32) -> SnakeBus {
        SnakeBus { mem: vec![0u8; 0x10000].into_boxed_slice().try_into().unwrap(), rng: seed as u64 | 1 }
    }

    /// xorshift 의사 난수. 하드웨어 난수 대신 쓴다.
    fn next_rand(&mut self) -> u8 {
        self.rng ^= self.rng << 13;
        self.rng ^= self.rng >> 7;
        self.rng ^= self.rng << 17;
        self.rng as u8
    }
}

impl Bus for SnakeBus {
    fn read(&mut self, addr: u16) -> u8 {
        if addr == 0xFE {
            self.next_rand() // 이 주소는 읽을 때마다 다른 난수가 나온다
        } else {
            self.mem[addr as usize]
        }
    }

    fn write(&mut self, addr: u16, val: u8) {
        self.mem[addr as usize] = val;
    }
}

/// CPU + SnakeBus = 게임이 돌아가는 가장 작은 컴퓨터.
pub struct SnakeMachine {
    pub cpu: Cpu,
    pub bus: SnakeBus,
    pub game_over: bool,
}

impl SnakeMachine {
    pub fn new(seed: u32) -> SnakeMachine {
        let mut bus = SnakeBus::new(seed);
        // 게임 코드를 $0600에 로드하고 그 주소에서 실행을 시작한다
        bus.mem[0x0600..0x0600 + SNAKE_GAME.len()].copy_from_slice(&SNAKE_GAME);
        let mut cpu = Cpu::new();
        cpu.pc = 0x0600;
        SnakeMachine { cpu, bus, game_over: false }
    }

    /// 마지막 키 입력을 $FF에 기록한다 (w/a/s/d의 아스키 코드)
    pub fn set_key(&mut self, key: u8) {
        self.bus.mem[0xFF] = key;
    }

    /// 명령어 n개를 실행한다. 게임 오버(BRK 도달)를 만나면 멈춘다.
    pub fn run(&mut self, instructions: u32) {
        for _ in 0..instructions {
            if self.bus.read(self.cpu.pc) == 0x00 {
                self.game_over = true; // 뱀이 죽으면 게임 코드가 BRK(0x00) 영역으로 점프한다
                return;
            }
            self.cpu.step(&mut self.bus);
        }
    }

    /// 화면 = $0200~$05FF의 1,024바이트. 한 바이트가 픽셀 하나다.
    pub fn screen(&self) -> &[u8] {
        &self.bus.mem[0x0200..0x0600]
    }

    /// 뱀의 길이 (게임이 $03에 저장한다)
    pub fn snake_len(&self) -> u8 {
        self.bus.mem[0x03]
    }
}
